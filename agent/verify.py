"""Deterministic checks (no LLM). The model proposes; this code disposes.

Two jobs:
  1. check_quote(): is the evidence quote an extractor gave us really in the document?
  2. verify_brief(): does the final brief obey the rules (cited, numbers traceable, short,
     conflicts surfaced)?
"""
from __future__ import annotations
import re

from config import MAX_WORDS

SECTIONS = ["snapshot", "bull case", "bear case", "open questions"]
TITLES = {"snapshot": "Snapshot", "bull case": "Bull case", "bear case": "Bear case",
          "open questions": "Open questions"}
HEAD = re.compile(r"^\s*(?:#{1,6}\s*)?(?:\*\*)?\s*(?:\d+[.)]\s*)?"
                  r"(snapshot|bull case|bear case|open questions|sources)\b", re.I)
CITE = re.compile(r"[\[(](S\d+(?:\.\d+)?(?:\s*[,;]\s*S\d+(?:\.\d+)?)*)[\])]")
ADVICE = re.compile(r"\b(buy|sell|hold rating|target price|should invest|we recommend)\b", re.I)


# ---------- text helpers ----------
def norm(t: str) -> str:
    t = t.lower()
    for a, b in {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
                 "\u2013": "-", "\u2014": "-", "\u00a0": " "}.items():
        t = t.replace(a, b)
    t = re.sub(r"[*_`#>]", "", t)
    return re.sub(r"\s+", " ", t).strip()


def numnorm(t: str) -> str:
    """Normalise a text so '1,234.5' and '1234.5' compare equal."""
    return re.sub(r"(?<=\d),(?=\d)", "", norm(t))


# ---------- 1. quote check ----------
def check_quote(evidence: str, doc_text: str) -> str:
    """'exact' | 'fuzzy' | 'fail'. Fuzzy tolerates tiny wording slips but never wrong numbers."""
    e, d = norm(evidence), norm(doc_text)
    if len(e) < 8:
        return "fail"
    parts = [p.strip() for p in re.split(r"\.{3}|…", e) if len(p.strip()) > 8]
    if parts and all(p in d for p in parts):
        return "exact"
    words = re.findall(r"\w+", e)
    dset = set(re.findall(r"\w+", d))
    frac = sum(w in dset for w in words) / max(len(words), 1)
    nums_ok = all(n in numnorm(doc_text) for n in numbers_in(e, strict=True))
    return "fuzzy" if frac >= 0.85 and nums_ok else "fail"


# ---------- 2. brief checks ----------
def numbers_in(text: str, strict: bool = False) -> list[str]:
    t = CITE.sub("", text)
    t = re.sub(r"\b(?:Q[1-4]|H[12]|FY|CY)\s?-?\d{0,4}\b", "", t, flags=re.I)  # Q1, FY27, FY2027
    out = []
    for n in re.findall(r"\d[\d,]*\.?\d*", t):
        n = n.replace(",", "").rstrip(".")
        if not n or re.fullmatch(r"(19|20)\d{2}", n):
            continue
        if not strict and "." not in n and len(n) == 1:   # ignore bare single digits ("3 plants")
            continue
        out.append(n)
    return out


def number_in_text(n: str, text_numnorm: str) -> bool:
    return re.search(r"(?<![\d.])" + re.escape(n) + r"(?!\d)", text_numnorm) is not None


def cites(line: str) -> list[str]:
    refs = []
    for m in CITE.finditer(line):
        for x in re.findall(r"S\d+", m.group(1)):
            if x not in refs:
                refs.append(x)
    return refs


def split_sections(md: str) -> dict:
    sections, cur = {}, None
    for line in md.splitlines():
        m = HEAD.match(line)
        if m and len(line.strip()) <= 40:
            cur = m.group(1).lower()
            sections.setdefault(cur, [])
        elif cur and line.strip():
            sections[cur].append(line.strip())
    sections.pop("sources", None)   # sources are generated by code, never by the model
    return sections


def verify_brief(sections: dict, docs: list[dict], analysis: dict | None = None) -> dict:
    analysis = analysis or {}
    errors, warnings = [], []
    by_id = {d["id"]: d for d in docs}
    texts = {i: numnorm(d["text"]) for i, d in by_id.items()}

    for name in SECTIONS:
        if not sections.get(name):
            errors.append(f"Missing or empty section: {TITLES[name]}")

    words = sum(len(l.split()) for n in SECTIONS for l in sections.get(n, []))
    if words > MAX_WORDS:
        errors.append(f"Too long: {words} words (limit {MAX_WORDS}). Cut the weakest points.")

    if len(sections.get("snapshot", [])) > 5:
        warnings.append("Snapshot is longer than 3-4 lines.")
    for n in ("bull case", "bear case"):
        if len(sections.get(n, [])) < 2:
            warnings.append(f"{TITLES[n]} has fewer than 2 points.")

    for name in SECTIONS:
        for line in sections.get(name, []):
            refs = cites(line)
            if not refs:
                if name != "open questions":
                    errors.append(f"[{TITLES[name]}] uncited line: \"{line[:70]}\"")
                continue
            bad = [r for r in refs if r not in by_id]
            if bad:
                errors.append(f"[{TITLES[name]}] cites unknown source {bad}: \"{line[:60]}\"")
            valid = [r for r in refs if r in by_id]
            for n in numbers_in(line):
                if valid and not any(number_in_text(n, texts[r]) for r in valid):
                    errors.append(f"[{TITLES[name]}] number '{n}' is not in cited source(s) {valid}: \"{line[:60]}\"")
            if ADVICE.search(line):
                warnings.append(f"Possible investment-advice wording: \"{line[:60]}\"")

    oq_refs = {r for l in sections.get("open questions", []) for r in cites(l)}
    for c in analysis.get("conflicts", []):
        srcs = [s for s in c.get("sources", []) if s in by_id]
        if len(srcs) >= 2 and not oq_refs.intersection(srcs):
            errors.append(f"Conflict on '{c.get('topic', '?')}' between {srcs} is not raised in Open questions")

    return {"ok": not errors, "errors": errors, "warnings": warnings, "words": words}


# ---------- final assembly ----------
def assemble(ticker: str, sections: dict, docs: list[dict], today) -> str:
    by_id = {d["id"]: d for d in docs}
    out = [f"# {ticker} — research brief (as of {today:%d %b %Y})", ""]
    cited = []
    for name in SECTIONS:
        out.append(f"## {TITLES[name]}")
        for line in sections.get(name, []):
            out.append(line)
            cited += [r for r in cites(line) if r not in cited and r in by_id]
        out.append("")
    out.append("## Sources")
    for r in sorted(cited, key=lambda x: int(x[1:])):
        d = by_id[r]
        note = f" — {d['tier_label']}" + (f"; ⚠ {', '.join(d['flags'])}" if d["flags"] else "")
        out.append(f"- **[{r}]** {d['source']} · {d['date_str']} · {d['url'] or 'no URL'}{note}")
    unused = [d["id"] for d in docs if d["id"] not in cited]
    if unused:
        out.append(f"- Reviewed but not cited: {', '.join(unused)}")
    return "\n".join(out)
